import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync } from 'node:fs'
import { mkdir, rename, rm, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import type { RunContext } from '../project/index.js'
import { parseStepTitle, type Spec, type SpecId } from '../spec/index.js'
import type { FailureRecord, RenderedTest } from '../workspace/index.js'

/**
 * Everything Libretto knows about invoking Playwright Test. The only module that spawns
 * `playwright test`. Takes `RunContext`, so it has no agent.
 */

export type WrapperMode =
  | { readonly kind: 'suite'; readonly specs: readonly Spec[] }
  | { readonly kind: 'draft'; readonly file: string; readonly storageState: string | null }
  | { readonly kind: 'fixtures'; readonly chain: readonly Spec[] }

interface PlannedProject {
  readonly name: string
  readonly files: readonly string[]
  readonly dependencies: readonly string[]
}

const setupName = (fixture: SpecId) => `setup:${fixture}`

/** One setup project per fixture, depending on its own `uses`. */
function setupProjects(ctx: RunContext, fixtures: readonly Spec[]): PlannedProject[] {
  const present = new Set(fixtures.map((f) => f.id))
  return fixtures.map((f) => ({
    name: setupName(f.id),
    files: [ctx.workspace.generatedFile(f.id)],
    dependencies: f.uses && present.has(f.uses) ? [setupName(f.uses)] : [],
  }))
}

/** Scenario specs grouped by innermost fixture, so each group depends on exactly one setup project. */
function scenarioProjects(ctx: RunContext, scenarios: readonly Spec[], fixtures: ReadonlySet<SpecId>): PlannedProject[] {
  const groups = new Map<SpecId | null, string[]>()
  for (const s of scenarios) {
    const files = groups.get(s.uses) ?? []
    files.push(ctx.workspace.generatedFile(s.id))
    groups.set(s.uses, files)
  }
  return [...groups].map(([uses, files]) => ({
    name: uses ? `scenarios:${uses}` : 'scenarios',
    files,
    dependencies: uses && fixtures.has(uses) ? [setupName(uses)] : [],
  }))
}

/**
 * The wrapper is evaluated by Playwright (in the runner and in every worker), so it is plain
 * `.mjs` with the plan embedded as data. It owns `testDir`/`testMatch`/`outputDir`/`projects`/
 * `reporter` and the `use` keys triage depends on, and spreads everything else from the user.
 */
function renderWrapper(plan: object, userConfigUrl: string | null): string {
  return `// Generated by libretto. Rewritten on every run. Do not edit.
const plan = ${JSON.stringify(plan, null, 2)}

const exact = (file) => new RegExp('^' + file.replace(/[.*+?^\${}()|[\\]\\\\]/g, '\\\\$&') + '$')
const loaded = ${userConfigUrl ? `await import(${JSON.stringify(userConfigUrl)})` : '{}'}
const { projects: userProjects = [], reporter: userReporter, ...user } = loaded.default ?? {}

if (userProjects.length > 0 && !process.env.TEST_WORKER_INDEX) {
  console.warn('warn: libretto runs its own Playwright projects and keeps only \`use\` from the first project in your playwright.config.')
}

const reporter = [
  ...(userReporter === undefined ? [['list']] : typeof userReporter === 'string' ? [[userReporter]] : userReporter),
  ...plan.reporters,
]

export default {
  ...user,
  testDir: plan.testDir,
  testMatch: '**/*.generated.spec.ts',
  outputDir: plan.outputDir,
  ...plan.limits,
  reporter: plan.reporter ?? reporter,
  use: {
    ...user.use,
    ...userProjects[0]?.use,
    baseURL: plan.baseURL,
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
    ...plan.use,
  },
  ...(plan.projects.length > 0 && {
    projects: plan.projects.map((p) => ({
      name: p.name,
      testMatch: p.files.map(exact),
      dependencies: p.dependencies,
    })),
  }),
}
`
}

/** Atomic and byte-identical on rewrite, so concurrent commands never see a torn file. */
async function writeIfChanged(file: string, content: string): Promise<void> {
  await mkdir(path.dirname(file), { recursive: true })
  const tmp = `${file}.${randomBytes(6).toString('hex')}.tmp`
  try {
    await writeFile(tmp, content)
    await rename(tmp, file)
  } catch (e) {
    await rm(tmp, { force: true })
    throw e
  }
}

function packageRoot(): string {
  let dir = path.dirname(fileURLToPath(import.meta.url))
  while (!existsSync(path.join(dir, 'package.json')) || JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')).name !== 'libretto') {
    const parent = path.dirname(dir)
    if (parent === dir) throw new Error('Cannot locate the libretto package root')
    dir = parent
  }
  return dir
}

/** Built entry points of this package. They exist in an installed package and after `pnpm build`. */
function builtEntries(): { test: string; reporter: string } {
  const dist = path.join(packageRoot(), 'dist')
  return { test: path.join(dist, 'test', 'index.js'), reporter: path.join(dist, 'run', 'reporter.js') }
}

/**
 * Generated files import `libretto/test` from `.libretto/generated/`. Node resolves that
 * by walking up, so a `libretto` package under `.libretto/node_modules/` is found first
 * without relying on the user's install layout (pnpm does not hoist) or on this repo
 * being a dependency of itself. The shim re-exports the built entry points by absolute
 * file URL, so the module instance (and its `@playwright/test`) is the real one.
 */
async function writeLibrettoShim(ctx: RunContext): Promise<void> {
  const dir = path.join(ctx.workspace.dir, 'node_modules', 'libretto')
  const entries = builtEntries()
  const reexport = (file: string) => `export * from ${JSON.stringify(pathToFileURL(file).href)}\n`
  const manifest = { name: 'libretto', type: 'module', exports: { './test': './test.js', './reporter': './reporter.js', './package.json': './package.json' } }
  await writeIfChanged(path.join(dir, 'package.json'), JSON.stringify(manifest, null, 2) + '\n')
  await writeIfChanged(path.join(dir, 'test.js'), reexport(entries.test))
  await writeIfChanged(
    path.join(dir, 'reporter.js'),
    `export { default } from ${JSON.stringify(pathToFileURL(entries.reporter).href)}\n`,
  )
}

/**
 * Writes the wrapper config and returns its path. Deterministic from inputs, so rewriting
 * it on every call is idempotent. Suite mode writes `.libretto/playwright.config.mjs`;
 * draft and fixtures runs get their own files so they never race a suite run.
 *
 * The wrapper imports the user's playwright.config (if any) and overrides only what
 * Libretto must own:
 * - `testDir` = generated (or drafts) dir, `testMatch` per project to the exact generated files
 * - `use.baseURL` = config.baseURL
 * - `use.trace = 'retain-on-failure'`, `use.screenshot = 'only-on-failure'`: triage depends on them
 * - `reporter` = user's reporters + `libretto/reporter` (suite mode only)
 * - `projects`: a setup project `setup:<fixture>` per fixture with `dependencies` mirroring
 *   `uses`, and `scenarios[:<fixture>]` projects that depend on their innermost fixture's setup.
 *   Deviation from the sketch: not multiplied by the user's projects (v1); only the first user
 *   project's `use` is kept, and the wrapper warns.
 *
 * Also writes the `libretto/test` resolution shim (see `writeLibrettoShim`).
 */
export async function writeWrapperConfig(ctx: RunContext, mode: WrapperMode): Promise<string> {
  const { workspace, config } = ctx
  await writeLibrettoShim(ctx)
  const base = { baseURL: config.baseURL, outputDir: path.join(workspace.dir, 'test-results'), limits: {}, use: {}, reporters: [] as unknown[], reporter: null as unknown, projects: [] as PlannedProject[] }
  let plan: typeof base & { testDir: string }
  let file: string
  switch (mode.kind) {
    case 'suite': {
      const fixtures = mode.specs.filter((s) => s.kind === 'fixture')
      const scenarios = mode.specs.filter((s) => s.kind === 'scenario')
      const options = { workspace: workspace.root, specsDir: workspace.specsDir, baseURL: config.baseURL }
      plan = {
        ...base,
        testDir: workspace.generatedDir,
        reporters: [[builtEntries().reporter, options]],
        projects: [...setupProjects(ctx, fixtures), ...scenarioProjects(ctx, scenarios, new Set(fixtures.map((f) => f.id)))],
      }
      file = 'playwright.config.mjs'
      break
    }
    case 'fixtures':
      plan = { ...base, testDir: workspace.generatedDir, projects: setupProjects(ctx, mode.chain) }
      file = 'playwright.fixtures.config.mjs'
      break
    case 'draft':
      plan = {
        ...base,
        testDir: workspace.draftsDir,
        limits: { retries: 0, workers: 1, fullyParallel: false },
        reporter: [['list']],
        use: mode.storageState ? { storageState: mode.storageState } : {},
        projects: [{ name: '', files: [mode.file], dependencies: [] }],
      }
      file = 'playwright.draft.config.mjs'
      break
  }
  const userUrl = config.playwrightConfig ? pathToFileURL(config.playwrightConfig).href : null
  const out = path.join(workspace.dir, file)
  await writeIfChanged(out, renderWrapper(plan, userUrl))
  return out
}

/**
 * The runner must be the `@playwright/test` that `libretto/test` imports, or Playwright
 * throws "did not expect test.describe() to be called here". Resolving from the built test
 * entry finds the user's copy in a normal install (it is a peer dependency) and Libretto's
 * own copy when Libretto is linked from a checkout.
 */
function resolvePlaywrightCli(): string {
  return createRequire(builtEntries().test).resolve('@playwright/test/cli')
}

function runCli(ctx: RunContext, wrapper: string, files: readonly string[], extraArgs: readonly string[], capture: boolean): Promise<{ code: number; output: string }> {
  const args = [resolvePlaywrightCli(), 'test', '-c', wrapper, ...files, ...extraArgs]
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, args, { cwd: ctx.config.root, stdio: capture ? ['ignore', 'pipe', 'pipe'] : 'inherit' })
    let output = ''
    child.stdout?.on('data', (d: Buffer) => void (output += d))
    child.stderr?.on('data', (d: Buffer) => void (output += d))
    const abort = () => child.kill('SIGTERM')
    if (ctx.signal?.aborted) abort()
    ctx.signal?.addEventListener('abort', abort, { once: true })
    child.on('error', reject)
    child.on('close', (code) => {
      ctx.signal?.removeEventListener('abort', abort)
      resolve({ code: code ?? 1, output })
    })
  })
}

/**
 * Spawns `node <@playwright/test cli> test -c <wrapper> [files] [...extraArgs]` with
 * inherited stdio. Resolves with Playwright's exit code. `ctx.signal` → SIGTERM to the child.
 */
export async function spawnPlaywright(ctx: RunContext, wrapper: string, files: readonly string[], extraArgs: readonly string[]): Promise<number> {
  return (await runCli(ctx, wrapper, files, extraArgs, false)).code
}

export type DraftResult =
  | { readonly passed: true }
  | { readonly passed: false; readonly failure: Pick<FailureRecord, 'scenario' | 'step' | 'error'>; readonly output: string }

const ANSI = /\u001b\[[0-9;]*m/g

/**
 * Best effort over the `list` reporter summary. Its first failure header reads
 * `1) [project] › file:line:col › scenario › Steps 2: text`: the trailing step title is
 * present when the failure happened inside a rendered step. The error is the text between
 * that header and the first code frame or stack frame.
 */
export function parseListFailure(rawOutput: string): Pick<FailureRecord, 'scenario' | 'step' | 'error'> {
  const output = rawOutput.replace(ANSI, '')
  const lines = output.split('\n')
  const headerAt = lines.findIndex((l) => /^\s*1\) /.test(l))
  const header = headerAt < 0 ? '' : (lines[headerAt] ?? '').replace(/^\s*1\)\s*/, '').replace(/\s*─+\s*$/, '').trim()
  const titles = header.split(' › ').filter((t) => t && !/^\[.*\]$/.test(t) && !/\.[cm]?[jt]sx?:\d+:\d+$/.test(t))
  const last = titles.at(-1)
  const stepTitle = last !== undefined && parseStepTitle('', last) ? titles.pop() : undefined
  const scenario = titles.at(-1) ?? ''
  const step = stepTitle === undefined ? null : parseStepTitle(scenario, stepTitle)

  const body: string[] = []
  for (const line of lines.slice(headerAt + 1)) {
    if (headerAt < 0 || /^\s+at /.test(line) || /^\s*>?\s*\d+ \|/.test(line) || /^\s+\d+ (failed|passed)/.test(line)) break
    body.push(line.replace(/^ {4}/, ''))
  }
  const message = body.join('\n').trim() || output.trim()
  return { scenario, step, error: { message, stack: null } }
}

/**
 * Used by `write_test.accept`: writes the draft to `.libretto/drafts/`, runs it once
 * (no retries, one worker, `list` reporter captured), and reports the first failure in
 * a form the agent can act on. Never touches `.libretto/generated/` or `last-run.json`.
 */
export async function runDraft(ctx: RunContext, draft: RenderedTest, specFile: string, storageState: string | null): Promise<DraftResult> {
  const file = await ctx.workspace.writeDraft(draft, specFile)
  const wrapper = await writeWrapperConfig(ctx, { kind: 'draft', file, storageState })
  const { code, output } = await runCli(ctx, wrapper, [file], [], true)
  if (code === 0) return { passed: true }
  const trimmed = output.replace(ANSI, '').trim()
  return { passed: false, failure: parseListFailure(output), output: trimmed }
}

/**
 * Runs the generated setup tests for `chain` (outermost first) so `generate` can start
 * an agent from the innermost fixture's storageState. Returns that state file's path,
 * or null for an empty chain.
 * Throws `FixtureNotReadyError` when a fixture in the chain is not `fresh` or its setup fails:
 * the dependent spec can't be generated against a broken setup.
 */
export async function prepareStorageState(ctx: RunContext, chain: readonly Spec[]): Promise<string | null> {
  const innermost = chain.at(-1)
  if (!innermost) return null
  for (const fixture of chain) {
    const state = await ctx.workspace.staleness(fixture, ctx.suite.app)
    if (state === 'missing') throw new FixtureNotReadyError(fixture.id, 'not-generated')
    if (state !== 'fresh') throw new FixtureNotReadyError(fixture.id, 'stale')
  }
  // A state file left by an earlier run would hide a setup that no longer produces one.
  await Promise.all(chain.map((f) => rm(ctx.workspace.stateFile(f.id), { force: true })))
  const wrapper = await writeWrapperConfig(ctx, { kind: 'fixtures', chain })
  const code = await spawnPlaywright(ctx, wrapper, chain.map((f) => ctx.workspace.generatedFile(f.id)), [])
  const missing = chain.find((f) => !existsSync(ctx.workspace.stateFile(f.id)))
  if (code !== 0 || missing) throw new FixtureNotReadyError((missing ?? innermost).id, 'setup-failed')
  return ctx.workspace.stateFile(innermost.id)
}

export class FixtureNotReadyError extends Error {
  override readonly name = 'FixtureNotReadyError'
  constructor(
    readonly fixture: SpecId,
    readonly why: 'not-generated' | 'stale' | 'setup-failed',
  ) {
    super(`Fixture ${fixture} is ${why}`)
  }
}
