import { describe, expect, it } from 'vitest'
import type { AppHash, SpecHash, SpecId } from '../spec/index.js'
import { parseHeader, renderHeader } from './header.js'

const id = 'auth/login' as SpecId
const specHash = '9f2c1a00ffee' as SpecHash
const appHash = 'c0de0000beef' as AppHash

describe('header', () => {
  it('round-trips the stamp and the body', () => {
    const body = "import { test } from 'libretto/test'\n\ntest('x', async () => {})\n"
    const text = renderHeader(id, 'specs/auth/login.md', specHash, appHash, body)
    const parsed = parseHeader(text)
    expect(parsed?.body).toBe(body)
    expect(parsed?.header).toMatchObject({ spec: id, specHash, appHash })
    expect(parsed?.header.bodyHash).toMatch(/^[0-9a-f]{64}$/)
  })

  it('writes the two human lines then the machine line', () => {
    const lines = renderHeader(id, 'specs/auth/login.md', specHash, appHash, 'body\n').split('\n')
    expect(lines[0]).toContain('GENERATED by libretto from specs/auth/login.md')
    expect(lines[1]).toContain('DO NOT EDIT')
    expect(lines[2]).toMatch(/^\/\/ libretto: \{.*"bodyHash"/)
    expect(lines[3]).toBe('body')
  })

  it('round-trips an empty body and a body with leading blank lines', () => {
    for (const body of ['', '\n\nx']) {
      expect(parseHeader(renderHeader(id, 'f.md', specHash, appHash, body))?.body).toBe(body)
    }
  })

  it('returns null without a valid header', () => {
    expect(parseHeader('')).toBeNull()
    expect(parseHeader("import x from 'y'\n")).toBeNull()
    const good = renderHeader(id, 'f.md', specHash, appHash, 'b\n')
    expect(parseHeader(good.replace('// libretto: {', '// libretto: {{'))).toBeNull()
    expect(parseHeader(good.replace('"bodyHash"', '"other"'))).toBeNull()
    expect(parseHeader(good.split('\n').slice(0, 2).join('\n'))).toBeNull()
  })
})
